-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT farm.ID AS ENTITY_ID, farm.NAME AS ENTITY_NAME,
       farm.REGION, farm.CATEGORY, farm.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(observation.WQ_EVENT_COUNT) AS WQ_EVENT_COUNT,
       SUM(observation.OPERATING_HOURS) AS OPERATING_HOURS,
       SUM(observation.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(observation.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(observation.PM_DUE) AS PM_DUE, SUM(observation.PM_COMPLETED) AS PM_COMPLETED,
       SUM(observation.PARAMETER_CHECKS) AS PARAMETER_CHECKS,
       SUM(observation.IN_BAND_READINGS) AS IN_BAND_READINGS, SUM(observation.PROBE_READINGS) AS PROBE_READINGS,
       SUM(observation.ALARM_CHECKS) AS ALARM_CHECKS,
       100.0 * SUM(observation.IN_BAND_READINGS) / NULLIF(SUM(observation.PROBE_READINGS), 0) AS IN_BAND_PCT,
       1000.0 * SUM(observation.ALARM_CHECKS) / NULLIF(SUM(observation.PARAMETER_CHECKS), 0) AS ALARMS_PER_1K,
       100.0 * SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.PLANNED_HOURS), 0) AS AERATION_UPTIME_PCT,
       100.0 * SUM(observation.PM_COMPLETED) / NULLIF(SUM(observation.PM_DUE), 0) AS PM_COMPLIANCE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.FARM_DAILY observation
JOIN RAW.FARMS farm ON farm.ID = observation.ENTITY_ID
GROUP BY farm.ID, farm.NAME, farm.REGION, farm.CATEGORY, farm.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(IN_BAND_READINGS) AS IN_BAND_READINGS, SUM(PROBE_READINGS) AS PROBE_READINGS,
       SUM(PARAMETER_CHECKS) AS PARAMETER_CHECKS, SUM(ALARM_CHECKS) AS ALARM_CHECKS,
       SUM(WQ_EVENT_COUNT) AS WQ_EVENT_COUNT,
       100.0 * SUM(IN_BAND_READINGS) / NULLIF(SUM(PROBE_READINGS), 0) AS IN_BAND_PCT
FROM RAW.FARM_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.WQ_EVENT_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(WQ_EVENT_COUNT) AS WQ_EVENT_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(PROBE_READINGS) - SUM(IN_BAND_READINGS) AS OUT_OF_BAND_READINGS
FROM RAW.FARM_DAILY
WHERE WQ_EVENT_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(IN_BAND_READINGS) AS IN_BAND_READINGS, SUM(PROBE_READINGS) AS PROBE_READINGS,
         SUM(PARAMETER_CHECKS) AS PARAMETER_CHECKS, SUM(ALARM_CHECKS) AS FAILED,
         SUM(WQ_EVENT_COUNT) AS WQ_EVENTS,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.FARM_DAILY
), network AS (SELECT COUNT(*) AS FARM_COUNT FROM RAW.FARMS),
readiness AS (
  SELECT 100.0 * SUM(LEAST(ON_HAND_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT
  FROM RAW.EQUIPMENT_READINESS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'In-Band Probe Readings' AS TITLE,
         100.0 * IN_BAND_READINGS / NULLIF(PROBE_READINGS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Water Quality Events', WQ_EVENTS, '' FROM observations
  UNION ALL SELECT 3, 'Alarms per 1k Parameter Checks', 1000.0 * FAILED / NULLIF(PARAMETER_CHECKS, 0), '' FROM observations
  UNION ALL SELECT 4, 'Probe Readings', PROBE_READINGS, '' FROM observations
  UNION ALL SELECT 5, 'Aeration Uptime', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Aquaculture Farms', FARM_COUNT, '' FROM network
  UNION ALL SELECT 7, 'Aeration Equipment Readiness', COVERAGE_PCT, '%' FROM readiness
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.TITLE = 'Alarms per 1k Parameter Checks' THEN TRIM(TO_VARCHAR(metrics.VALUE_NUM, '990.00'))
                WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.WQ_EVENT_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
